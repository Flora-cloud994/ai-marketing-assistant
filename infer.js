/* 服装词是最强的特征：说「XX裤」「XX裙」几乎一定是衣服。
   但「裤架」「帽架」是收纳，要排掉，否则家居收纳会被抢成服饰。
   放在所有画像之前判断，免得「儿童背带裤」被玩具画像的「儿童」抢走。 */
const GARMENT_RE = /(?:裤|裙|衬衫|T恤|t恤|卫衣|外套|背心|吊带|内衣|睡衣|泳衣|防晒衣|冲锋衣|帆布鞋|运动鞋|靴|帽)(?!架|柜|盒|钩|夹|撑|收纳)/;

/* 用户的说法常常就是画像的展示名（「彩妆」「手电」「路由」「纸品」），
   但画像的正则写的是具体款式词，会漏掉这些「品类口语名」。
   先把展示名做成字典直查，两字以上才进——单字（鞋/袜/帽）太泛，交给下面的规则。 */
const NAME_IDX = (() => {
  const m = {};
  ALL_PROFILES.forEach(p => {
    const zh = String(p.zh || '').split(/\s*\/\s*/)[0].trim();
    if (zh.length >= 2 && !m[zh]) m[zh] = p;
  });
  return m;
})();
const NAME_KEYS = Object.keys(NAME_IDX).sort((a, b) => b.length - a.length);
function byName(s) {
  if (s.length < 2) return null;
  for (const k of NAME_KEYS) if (s.indexOf(k) > -1) return NAME_IDX[k];
  return null;
}

function inferCat(text) {
  const s = String(text || '');
  const pick = p => ({ cat: p.cat, en: p.en, band: p.band, hit: p.id });
  /* 口语品类名先直查：「彩妆」「手电」「路由」这类词，正则里往往没写 */
  const named = byName(s);
  if (named) return pick(named);
  /* 长尾画像最具体，先匹配：「背带裤」要能命中 overalls，而不是被「裤」带去通用服饰 */
  for (const p of EXT_PROFILES) if (p.re.test(s)) return pick(p);
  /* 走到这里说明没有更具体的形态，才按「是不是衣服」粗判。
     「裤架」「帽架」这类会被上面的 hanger 先接走，这里是第二道保险。 */
  if (GARMENT_RE.test(s)) return { cat: '服饰配饰', en: 'everyday apparel', band: [16, 42], hit: 'apparel' };
  for (const p of PROFILES) if (p.re.test(s)) return pick(p);
  for (const [re, cat, band] of FALLBACK_RULES) if (re.test(s)) return { cat, en: '', band, hit: '' };
  /* 全都没命中就老实说「不确定」，不要硬塞一个品类让用户以为识别对了 */
  return { cat: '', en: '', band: [19, 39], hit: 'none' };
}

/* ---------- 联网兜底：本地认不出来，就去网上问一遍 ----------
   snips 来自本地抓取桥 /search，形如 [{t:标题, s:摘要, w:权重}]。
   同一条结果里，一个品类被几条画像同时命中只算一票 —— 否则宠物用品
   这种画像多的品类会无脑霸榜。百科/电商条目的权重更高，因为它们是定义句
   或商品名，比一篇「十大品牌」软文更能说明这是什么东西。            */
function voteCategory(snips) {
  const list = (snips || []).filter(x => x && (x.t || x.s));
  if (list.length < 2) return null;
  const catT = {}, idT = {};
  list.forEach(x => {
    const t = (x.t || '') + ' ' + (x.s || '');
    const w = Number(x.w) || 1;
    const cats = new Set(), ids = new Set();
    ALL_PROFILES.forEach(p => { if (p.re.test(t)) { cats.add(p.cat); ids.add(p.id); } });
    cats.forEach(c => { catT[c] = (catT[c] || 0) + w; });
    ids.forEach(id => { idT[id] = (idT[id] || 0) + w; });
  });
  const rank = Object.keys(catT).map(c => ({ cat: c, n: catT[c] })).sort((a, b) => b.n - a.n);
  if (!rank.length) return null;
  const top = rank[0], second = rank[1] || { cat: '', n: 0 };
  /* 该品类下被提到最多的那条画像，拿它去抓竞品比拿类目第一条准 */
  const id = Object.keys(idT)
    .filter(i => (ALL_PROFILES.find(p => p.id === i) || {}).cat === top.cat)
    .sort((a, b) => idT[b] - idT[a])[0] || '';
  return {
    cat: top.cat, id, n: top.n, of: list.length,
    second: second.cat, secondN: second.n,
    /* 只有「至少 3 条且领先亚军」才算认出来；平票说明这词天然跨类目，宁可不认 */
    ok: top.n >= 3 && top.n > second.n
  };
}


/* 价格带 → 建议定价（取中位，收成整数；美国站习惯 .99） */
function bandPrice(band, fx) {
  const lo = Math.max(9, Math.round(band[0] * fx));
  const hi = Math.max(lo + 6, Math.round(band[1] * fx));
  const mid = Math.round((lo + hi) / 2);
  return { lo, hi, mid };
}

