function benefitHits(products) {
  const list = products || [];
  const n = list.length;
  return BENEFIT_KEYS.map(k => ({ cn: k.cn, keys: k.keys, n: list.filter(p => k.en.test(String(p.title || ''))).length }))
    .filter(x => x.n > 0).sort((a, b) => b.n - a.n).slice(0, 4)
    .map(x => ({ cn: x.cn, keys: x.keys, n: x.n, of: n }));
}

/* products: [{title, price, rating, reviews}] */
function refineByProfile(prof, products) {
  const list = (products || []).filter(p => p && p.title);
  if (!list.length) return null;
  const prices = list.map(p => Number(p.price) || 0).filter(x => x > 0).sort((a, b) => a - b);
  const reviews = list.map(p => Number(p.reviews) || 0).filter(x => x >= 0).sort((a, b) => a - b);
  const q = (arr, r) => arr.length ? arr[Math.min(arr.length - 1, Math.max(0, Math.round((arr.length - 1) * r)))] : 0;
  const hit = benefitHits(list);
  const med = reviews.length ? q(reviews, .5) : 0;
  const comp = med >= 2000 ? '高' : (med >= 300 ? '中' : '低');

  let band = prof.band.slice(), price = prof.price;
  if (prices.length >= 2) {
    let lo = Math.round(q(prices, .2)), hi = Math.round(q(prices, .8));
    /* 首屏 6 款常常挤在一个价位上，直接把带宽压成一条线（$34–40）就没法用来定价了。
       样本小的时候按中位给一个至少 ±12% 的带宽，让「低于中位」「高于白牌」有落点 */
    const mid0 = (lo + hi) / 2;
    const minW = Math.max(6, Math.round(mid0 * 0.24));
    if (hi - lo < minW) { lo = Math.round(mid0 - minW / 2); hi = Math.round(mid0 + minW / 2); }
    if (hi - lo >= 4) { band = [lo, hi]; price = Math.round((lo + hi) / 2); }
  }
  /* 真实标题里出现最多的卖点，挪到前面；其余保持原序 */
  let pts = prof.pts.slice();
  if (hit.length) {
    const score = p => {
      const i = hit.findIndex(h => h.keys.some(k => p.indexOf(k) > -1));
      return i < 0 ? 99 : i;
    };
    pts = pts.map((p, i) => ({ p, s: score(p), i })).sort((a, b) => (a.s - b.s) || (a.i - b.i)).map(x => x.p);
  }
  return {
    band, price, comp, medianReviews: med, hit,
    sample: list.slice(0, 3).map(p => ({ title: String(p.title).slice(0, 60), price: Number(p.price) || 0, reviews: Number(p.reviews) || 0 })),
    n: list.length,
    pts
  };
}
